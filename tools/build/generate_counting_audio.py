"""Build local counting MP3s. See assets/audio/README.md for setup/provenance.

Models and Python dependencies are build-only and never shipped to learners.
"""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
WORDS = {
    "en": "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen twenty".split(),
    "es": "cero uno dos tres cuatro cinco seis siete ocho nueve diez once doce trece catorce quince dieciséis diecisiete dieciocho diecinueve veinte".split(),
}

def normalize(text):
    return re.sub(r"\s+", " ", text).strip()

def scripts():
    result = {language: set(words) for language, words in WORDS.items()}
    for language, folder in [("en", "lessons"), ("es", "translations/es")]:
        for path in sorted((ROOT / "curriculum" / folder).glob("lesson000*.json")):
            for screen in json.loads(path.read_text())["screens"]:
                for key in ["audio", "correctFeedback", "wrongFeedback", "tooManyFeedback", "tooFewFeedback"]:
                    if screen.get(key): result[language].add(normalize(screen[key]))
                result[language].update(normalize(h) for h in screen.get("hints", []))
                for choice in screen.get("choices", []):
                    result[language].add(normalize(choice["text"]))
                    if choice.get("feedback"): result[language].add(normalize(choice["feedback"]))
        result[language].update([str(n) for n in range(21)])
    return result

def catalog():
    return {lang: {text: f"assets/audio/{lang}/{hashlib.sha256((lang + ':' + text).encode()).hexdigest()[:20]}.mp3"
                   for text in sorted(texts) if text} for lang, texts in scripts().items()}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model")
    parser.add_argument("--voices")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--decode", action="store_true", help="With --check, decode every clip through ffmpeg")
    parser.add_argument("--shards", type=int, default=1)
    parser.add_argument("--shard", type=int, default=0)
    args = parser.parse_args()
    entries = catalog()
    manifest = ROOT / "assets/audio/catalog.js"
    content = "// Generated by tools/build/generate_counting_audio.py; do not hand-edit.\nexport const countingAudio = " + json.dumps(entries, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        assert manifest.read_text() == content, "Audio catalog is stale"
        missing = [path for texts in entries.values() for path in texts.values() if not (ROOT / path).is_file()]
        assert not missing, f"Missing audio: {missing[:5]}"
        assert all((ROOT / path).stat().st_size > 1000 for texts in entries.values() for path in texts.values()), "Empty/truncated clip"
        if args.decode:
            with tempfile.TemporaryDirectory() as folder:
                playlist = pathlib.Path(folder) / "clips.txt"
                playlist.write_text("".join(f"file '{ROOT / path}'\n" for texts in entries.values() for path in texts.values()))
                subprocess.run(["ffmpeg", "-v", "error", "-xerror", "-f", "concat", "-safe", "0", "-i", str(playlist), "-f", "null", "-"], check=True)
        print(f"Audio catalog current: {sum(map(len, entries.values()))} clips")
        return
    import numpy as np
    import onnxruntime as rt
    import soundfile as sf
    from kokoro_onnx import Kokoro
    options = rt.SessionOptions()
    options.intra_op_num_threads = 2
    options.inter_op_num_threads = 1
    session = rt.InferenceSession(args.model, sess_options=options, providers=["CPUExecutionProvider"])
    class FloatSpeedSession:
        # kokoro-onnx 0.4.9 casts newer-export speed to int; the v1.1 export expects float.
        def __getattr__(self, key): return getattr(session, key)
        def run(self, outputs, inputs):
            inputs["speed"] = np.array([0.94], dtype=np.float32)
            return session.run(outputs, inputs)
    model = Kokoro.from_session(FloatSpeedSession(), args.voices)
    total = sum(map(len, entries.values()))
    index = 0
    for language, texts in entries.items():
        voice, locale = ("af_heart", "en-us") if language == "en" else ("ef_dora", "es")
        for text, relative in texts.items():
            index += 1
            if (index - 1) % args.shards != args.shard: continue
            path = ROOT / relative
            if path.exists() and path.stat().st_size > 1000: continue
            path.parent.mkdir(parents=True, exist_ok=True)
            spoken = re.sub(r"\b(\d{1,2})\b", lambda m: WORDS[language][int(m[0])] if int(m[0]) <= 20 else m[0], text)
            samples, rate = model.create(spoken, voice=voice, speed=1, lang=locale)
            assert len(samples) > rate * .1 and np.isfinite(samples).all(), f"Invalid audio: {text}"
            assert np.max(np.abs(samples)) > .005, f"Silent audio: {text}"
            samples = np.pad(samples, (int(rate * .08), int(rate * .12)))
            with tempfile.TemporaryDirectory() as folder:
                wav = pathlib.Path(folder) / "clip.wav"
                sf.write(wav, samples, rate)
                temporary = path.with_suffix(".tmp.mp3")
                subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-af", "loudnorm=I=-19:TP=-2:LRA=7", "-ar", "24000", "-codec:a", "libmp3lame", "-b:a", "64k", str(temporary)], check=True)
                temporary.replace(path)
            if index % 25 == 0: print(f"Generated {index}/{total}", flush=True)
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(content)
    print(f"Generated {total} clips", flush=True)

if __name__ == "__main__": main()
